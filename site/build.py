#!/usr/bin/env python3
"""Build the website's privacy page from the policy the app ships.

    python3 site/build.py           # rewrite site/public/privacy/index.html
    python3 site/build.py --check   # exit 1 if that file is out of date

The wording lives in one place: ios/ShiftEze/Resources/PrivacyPolicy.md.
Understands the same small Markdown subset as the app: `#` and `###`
headings, `-` bullets, and inline bold, italics and links.
"""

import html
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "ios" / "ShiftEze" / "Resources" / "PrivacyPolicy.md"
OUTPUT = ROOT / "site" / "public" / "privacy" / "index.html"

PAGE = """<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Privacy policy · FlixShift</title>
  <meta name="description" content="What FlixShift stores, what leaves your phone, and what it never does.">
  <meta name="theme-color" content="#050b18">
  <link rel="icon" href="/assets/favicon.png">
  <link rel="stylesheet" href="/styles.css">
</head>
<body>
  <!-- Generated by site/build.py from ios/ShiftEze/Resources/PrivacyPolicy.md. Edit that file, not this one. -->
  <div class="wrap">
    <header class="site">
      <a class="brand" href="/"><img src="/assets/icon.png" alt="" width="40" height="40">FlixShift</a>
      <nav><a href="/">Home</a><a href="mailto:support@flixshift.app">Contact</a></nav>
    </header>
    <main class="prose">
{body}
    </main>
  </div>
</body>
</html>
"""


def inline(text):
    text = html.escape(text, quote=False)
    text = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", r'<a href="\2">\1</a>', text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    return re.sub(r"\*(.+?)\*", r"<em>\1</em>", text)


def render(markdown):
    out, in_list = [], False
    for line in markdown.splitlines():
        if not line.strip():
            continue
        bullet = line.startswith("- ")
        if in_list and not bullet:
            out.append("      </ul>")
        if bullet and not in_list:
            out.append("      <ul>")
        in_list = bullet
        if bullet:
            out.append(f"        <li>{inline(line[2:])}</li>")
        elif line.startswith("### "):
            out.append(f"      <h3>{inline(line[4:])}</h3>")
        elif line.startswith("# "):
            out.append(f"      <h1>{inline(line[2:])}</h1>")
        else:
            out.append(f"      <p>{inline(line)}</p>")
    if in_list:
        out.append("      </ul>")
    return PAGE.format(body="\n".join(out))


def main(argv):
    page = render(SOURCE.read_text(encoding="utf-8"))
    if "--check" in argv:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != page:
            print("site/public/privacy/index.html is out of date. Run: python3 site/build.py")
            return 1
        print("site/public/privacy/index.html matches the app's policy.")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(page, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
